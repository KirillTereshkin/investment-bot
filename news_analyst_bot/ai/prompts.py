"""Промпты для DeepSeek.

SYSTEM_PROMPT задаёт роль аналитика российского рынка и строгий JSON-формат ответа.
USER_PROMPT_TEMPLATE подставляет окно, дайджест и рыночный контекст.
"""

from __future__ import annotations

SYSTEM_PROMPT = """
Ты — аналитик российского фондового рынка. Твоя задача — по дайджесту новостей за последний период выдавать краткий торговый прогноз по инструментам, доступным в Тинькофф Инвестициях.

Горизонт: среднесрочный и долгосрочный (от 2 недель до 6 месяцев). Внутридневную спекуляцию игнорируй.

Правила:
1. Анализируй только те новости, которые реально влияют на фундаментал: ставка ЦБ, инфляция, санкции, отчётности, дивиденды, регуляторика, ключевые макро-данные, геополитика.
2. Игнорируй шум: мелкие корпоративные пресс-релизы, повторные публикации, кликбейт.
3. Если новостей, значимых для торговли, нет — так и напиши: "Сигналов нет". Не выдумывай сделки ради ответа.
4. Используй только реально существующие тикеры MOEX (SBER, GAZP, LKOH, ROSN, GMKN, YDEX, T, VTBR, MTSS, PLZL, NVTK, SNGS, AFLT) и инструменты: акции, ОФЗ, фонды (TMOS, TRUR, TBRU), валюта (USD/RUB, CNY/RUB), фьючерсы.
5. Не давай рекомендаций по инструментам, которых нет в Тинькофф Инвестициях.
6. Указывай уверенность честно: если новость слабая — низкая уверенность. Не завышай. "Высокая уверенность" — максимум 1 идея за раз.
7. Пиши кратко. Максимум — 4 идеи за раз. Если идей меньше — не добивай до четырёх.

Формат ответа — строго JSON:
{
  "дата": "YYYY-MM-DD HH:MM MSK",
  "резюме_рынка": "1-2 предложения",
  "идеи": [
    {
      "инструмент": "SBER",
      "тип": "акция",
      "направление": "лонг|шорт|наблюдать",
      "горизонт": "2-8 недель",
      "уверенность": "низкая|средняя|высокая",
      "обоснование": "1-2 предложения, только суть",
      "триггер_отмены": "что отменит идею"
    }
  ],
  "урок_дня": "одна короткая фраза-наблюдение про рынок",
  "сигналов_нет": false
}
"""

USER_PROMPT_TEMPLATE = """
Новости за период {window_start}–{window_end} МСК:

{digest}

Контекст: ключевая ставка ЦБ сейчас {key_rate}%, индекс MOEX {moex_value} ({moex_change}% за сутки), USD/RUB {usdrub}.

Дай прогноз по формату.
"""

# DeepSeek требует, чтобы слово "json" встречалось в сообщениях при
# response_format={"type": "json_object"} — иначе API вернёт ошибку.
JSON_FORMAT_HINT = "Ответ верни строго в формате json, без markdown-обёртки и пояснений."


def build_user_prompt(
    *,
    window_start: str,
    window_end: str,
    digest: str,
    key_rate: float,
    moex_value: float,
    moex_change: float,
    usdrub: float,
) -> str:
    """Собирает пользовательский промпт из шаблона + требование json-формата."""
    prompt = USER_PROMPT_TEMPLATE.format(
        window_start=window_start,
        window_end=window_end,
        digest=digest,
        key_rate=key_rate,
        moex_value=moex_value,
        moex_change=moex_change,
        usdrub=usdrub,
    )
    return f"{prompt.strip()}\n\n{JSON_FORMAT_HINT}"
